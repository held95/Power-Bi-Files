import fitz  # PyMuPDF
import re
import os
from openpyxl import Workbook

# Caminho da pasta com os PDFs
pasta_pdfs = "/mnt/data"

# Criar planilha
wb = Workbook()
ws = wb.active
ws.title = "Dados"
ws.append(["Arquivo", "Compensação", "Consumo", "Saldo", "UC"])

# Expressões ajustadas com maior flexibilidade
padrao_uc = r"\b(\d{10})\b"
padrao_consumo = r"Consumo\s*-\s*TE\s*[A-Z]{3}/\d{2}.*?([\d.]+)"
padrao_compensacao = r"Energ\s+Atv\s+Inj\.\s+oUC\s+mPT\s*-\s*TUSD\s*[A-Z]{3}/\d{2}.*?([\d.]+)"
padrao_saldo = r"Saldo em Energia.*?:.*?([\d.,]+)"

# Processar todos os PDFs da pasta
for nome_arquivo in os.listdir(pasta_pdfs):
    if nome_arquivo.lower().endswith(".pdf"):
        caminho_pdf = os.path.join(pasta_pdfs, nome_arquivo)
        try:
            doc = fitz.open(caminho_pdf)
            texto = ""
            for pagina in doc:
                texto += pagina.get_text()

            # Aplicar regex
            uc = re.search(padrao_uc, texto)
            consumo = re.search(padrao_consumo, texto, re.IGNORECASE | re.DOTALL)
            compensacao = re.search(padrao_compensacao, texto, re.IGNORECASE | re.DOTALL)
            saldo = re.search(padrao_saldo, texto, re.IGNORECASE)

            # Extrair valores
            uc_val = uc.group(1) if uc else ""
            consumo_val = consumo.group(1) if consumo else ""
            compensacao_val = compensacao.group(1) if compensacao else ""
            saldo_val = saldo.group(1) if saldo else ""

            # Adicionar à planilha
            ws.append([nome_arquivo, compensacao_val, consumo_val, saldo_val, uc_val])

        except Exception as e:
            print(f"Erro ao processar {nome_arquivo}: {e}")

# Salvar planilha
caminho_saida = os.path.join(pasta_pdfs, "dados_extraidos_todos.xlsx")
wb.save(caminho_saida)
print("✔ Planilha final criada com sucesso!")