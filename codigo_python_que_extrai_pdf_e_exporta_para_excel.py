import fitz  # PyMuPDF
import re
from openpyxl import Workbook

# Abrir o PDF
caminho_pdf = "/Conta 3 IRMAOS - Mar.pdf"  # Altere o caminho se necessário
doc = fitz.open(caminho_pdf)

# Expressões para encontrar os valores
padrao_uc = r"UC\s*[:\-]?\s*(\d+)"
padrao_compensacao = r"compensação\s*[:\-]?\s*([\d,\.]+)"
padrao_consumo = r"consumo\s*[:\-]?\s*([\d,\.]+)"
padrao_saldo = r"saldo\s*[:\-]?\s*([\d,\.\-]+)"

# Lista para armazenar os dados
dados_extraidos = []

# Extrair texto de cada página
for pagina in doc:
    texto = pagina.get_text()

    ucs = re.findall(padrao_uc, texto, re.IGNORECASE)
    compensacoes = re.findall(padrao_compensacao, texto, re.IGNORECASE)
    consumos = re.findall(padrao_consumo, texto, re.IGNORECASE)
    saldos = re.findall(padrao_saldo, texto, re.IGNORECASE)

    # Combinar os dados de forma segura
    for i in range(min(len(ucs), len(compensacoes), len(consumos), len(saldos))):
        dados_extraidos.append([
            compensacoes[i],
            consumos[i],
            saldos[i],
            ucs[i]
        ])

# Criar e salvar a planilha
wb = Workbook()
ws = wb.active
ws.title = "Dados"

# Cabeçalhos
ws.append(["Compensação", "Consumo", "Saldo", "UC"])

# Adicionar os dados extraídos
for linha in dados_extraidos:
    ws.append(linha)

# Salvar o arquivo
wb.save("dados_extraidos(2).xlsx")
print("Planilha criada com sucesso!")

